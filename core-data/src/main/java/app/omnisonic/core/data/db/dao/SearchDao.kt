/**
 * Local-library search (K7: query-at-will LIKE, no server round trip, no FTS).
 *
 * Each `...Raw` query is generated by Room and takes one token pair per slot
 * (a missing slot carries NULL so its AND group passes) plus the scope's
 * excluded provider ids as a CSV string: API 29's SQLite 3.22 caps statements
 * at 999 bound variables (`docs/omnisonic/storage/sqlite-api29-floor.md`), so
 * the tiny provider set is matched with `instr(',' || csv || ',', ',' || id || ',')`
 * instead of a parameterized NOT IN list — leading/trailing commas make the
 * id match exact.
 *
 * The `search...Rows` methods are the catalog surface: they take a
 * [ProfileScope] and the token list, and are the only intended entry points
 * (`ProfileScopeQueryTest` enforces the pairing for every new catalog read).
 */
@Dao
interface SearchDao {

    @Query(
        """
        SELECT * FROM songs
        WHERE instr(',' || :excludedProviderIdsCsv || ',', ',' || providerId || ',') = 0
            AND (
                :raw1 IS NULL
                OR title LIKE :raw1 ESCAPE '\'
                OR title LIKE :normalized1 ESCAPE '\'
                OR latinTitle LIKE :raw1 ESCAPE '\'
                OR latinTitle LIKE :normalized1 ESCAPE '\'
                OR sortTitle LIKE :raw1 ESCAPE '\'
                OR sortTitle LIKE :normalized1 ESCAPE '\'
                OR displayArtist LIKE :raw1 ESCAPE '\'
            )
            AND (
                :raw2 IS NULL
                OR title LIKE :raw2 ESCAPE '\'
