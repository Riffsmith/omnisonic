                OR latinTitle LIKE :raw3 ESCAPE '\'
                OR latinTitle LIKE :normalized3 ESCAPE '\'
                OR sortTitle LIKE :raw3 ESCAPE '\'
                OR sortTitle LIKE :normalized3 ESCAPE '\'
                OR displayArtist LIKE :raw3 ESCAPE '\'
            )
            AND (
                :raw4 IS NULL
