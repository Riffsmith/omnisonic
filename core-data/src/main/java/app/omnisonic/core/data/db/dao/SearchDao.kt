                OR latinTitle LIKE :raw6 ESCAPE '\'
                OR latinTitle LIKE :normalized6 ESCAPE '\'
                OR sortTitle LIKE :raw6 ESCAPE '\'
                OR sortTitle LIKE :normalized6 ESCAPE '\'
                OR displayArtist LIKE :raw6 ESCAPE '\'
            )
        ORDER BY (lastPlayed IS NULL) ASC, lastPlayed DESC, COALESCE(sortTitle, title) COLLATE NOCASE, id
        LIMIT :limit OFFSET :offset
        """,
    )
    suspend fun searchSongRowsRaw(
        excludedProviderIdsCsv: String,
        raw1: String?,
        normalized1: String?,
        raw2: String?,
        normalized2: String?,
        raw3: String?,
        normalized3: String?,
        raw4: String?,
        normalized4: String?,
        raw5: String?,
        normalized5: String?,
        raw6: String?,
        normalized6: String?,
        limit: Int,
        offset: Int,
    ): List<SongEntity>

    suspend fun searchSongRows(
        scope: ProfileScope,
        terms: List<SearchTerm>,
        limit: Int,
        offset: Int,
    ): List<SongEntity> {
        if (terms.isEmpty()) return emptyList()
        val slots = terms.padToSlots()
        return searchSongRowsRaw(
            excludedProviderIdsCsv = scope.excludedProviderIds.joinToString(","),
            raw1 = slots[0]?.likePattern,
            normalized1 = slots[0]?.normalizedLikePattern,
            raw2 = slots[1]?.likePattern,
            normalized2 = slots[1]?.normalizedLikePattern,
            raw3 = slots[2]?.likePattern,
            normalized3 = slots[2]?.normalizedLikePattern,
            raw4 = slots[3]?.likePattern,
            normalized4 = slots[3]?.normalizedLikePattern,
            raw5 = slots[4]?.likePattern,
            normalized5 = slots[4]?.normalizedLikePattern,
            raw6 = slots[5]?.likePattern,
            normalized6 = slots[5]?.normalizedLikePattern,
            limit = limit,
            offset = offset,
        )
    }

